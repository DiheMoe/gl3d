// Command huffgen 从 minimp3.h(CC0,https://github.com/lieff/minimp3)提取 MP3
// Huffman 码表,生成 huffman_tables.go。在仓库根目录运行:
//
//	go -C tools run ./huffgen /path/to/minimp3.h | gofmt > huffman_tables.go
//
// 输出是 ISO/IEC 11172-3 Table B.7 形式的完整码字列表,不沿用 minimp3 的压缩树表示。
package main

import (
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

// extractCArray 抽取 C 源中 name[] = { ... } 的整数列表。
func extractCArray(src, name string) []int {
	re := regexp.MustCompile(regexp.QuoteMeta(name) + `\[[^\]]*\]\s*=\s*\{([^}]*)\}`)
	m := re.FindStringSubmatch(src)
	if m == nil {
		fatal("array %s not found", name)
	}
	var out []int
	for _, tok := range strings.Split(m[1], ",") {
		tok = strings.TrimSpace(tok)
		if tok == "" {
			continue
		}
		v, err := strconv.Atoi(tok)
		if err != nil {
			fatal("array %s: bad token %q", name, tok)
		}
		out = append(out, v)
	}
	return out
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "huffgen: "+format+"\n", args...)
	os.Exit(1)
}

type pairEntry struct {
	code, length, x, y int
}

// walkPairs 展开 minimp3 的 big_values 压缩树:非负条目是叶子(>>8 为本层消耗的
// 位数,低两个半字节为 x、y),负条目是链接(&7 为下一层宽度,-(>>3) 为偏移)。
// 叶子短于本层宽度时相邻下标重复同一码字,按码字去重。
func walkPairs(cb []int, off, width, prefix, prefixLen int, out *[]pairEntry) {
	prevCode, prevLen := -1, -1
	for idx := 0; idx < 1<<width; idx++ {
		e := cb[off+idx]
		if e >= 0 {
			nbits := e >> 8
			if nbits <= 0 || nbits > width {
				fatal("pair tree: level length %d inconsistent with width %d", nbits, width)
			}
			code := prefix<<nbits | idx>>(width-nbits)
			if code == prevCode && prefixLen+nbits == prevLen {
				continue
			}
			prevCode, prevLen = code, prefixLen+nbits
			*out = append(*out, pairEntry{code, prefixLen + nbits, e & 15, (e >> 4) & 15})
		} else {
			walkPairs(cb, -(e >> 3), e&7, prefix<<width|idx, prefixLen+width, out)
			prevCode, prevLen = -1, -1
		}
	}
}

type quadEntry struct {
	code, length, flags int
}

// walkQuads 展开 count1 压缩树:叶子(&8 置位)的 &7 为码字总长,高 4 位为四个值的
// 非零标志;链接的 >>3 为偏移、&3 为宽度。重复条目按码字去重。
func walkQuads(cb []int, off, width, prefix, prefixLen int, out *[]quadEntry) {
	prevCode, prevLen := -1, -1
	for idx := 0; idx < 1<<width; idx++ {
		e := cb[off+idx]
		if e&8 != 0 {
			total := e & 7
			nbits := total - prefixLen
			if nbits <= 0 || nbits > width {
				fatal("quad tree: total %d inconsistent with path %d+%d", total, prefixLen, width)
			}
			code := prefix<<nbits | idx>>(width-nbits)
			if code == prevCode && total == prevLen {
				continue
			}
			prevCode, prevLen = code, total
			*out = append(*out, quadEntry{code, total, e >> 4})
		} else {
			walkQuads(cb, e>>3, e&3, prefix<<width|idx, prefixLen+width, out)
			prevCode, prevLen = -1, -1
		}
	}
}

// checkCode 校验码表是完备前缀码:任一码字都不是另一码字的前缀,且码长满足
// Kraft 等式 Σ2^-len = 1,任何位模式都恰好匹配一个码字。
func checkCode(name string, n int, word func(i int) (code, length int)) {
	var kraft uint64
	for i := 0; i < n; i++ {
		ci, li := word(i)
		for j := 0; j < i; j++ {
			cj, lj := word(j)
			short, ls, long, ll := cj, lj, ci, li
			if ls > ll {
				short, ls, long, ll = ci, li, cj, lj
			}
			if long>>(ll-ls) == short {
				fatal("%s: codeword %#x/%d is a prefix of %#x/%d", name, short, ls, long, ll)
			}
		}
		kraft += 1 << (32 - li)
	}
	if kraft != 1<<32 {
		fatal("%s: Kraft sum %g, want 1", name, float64(kraft)/(1<<32))
	}
}

func main() {
	if len(os.Args) != 2 {
		fatal("usage: huffgen /path/to/minimp3.h")
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fatal("%v", err)
	}
	src := string(raw)

	tabs := extractCArray(src, "tabs")
	tabindex := extractCArray(src, "tabindex")
	linbits := extractCArray(src, "g_linbits")
	tab32 := extractCArray(src, "tab32")
	tab33 := extractCArray(src, "tab33")
	if len(tabindex) != 32 || len(linbits) != 32 {
		fatal("tabindex/linbits: want 32 entries, got %d/%d", len(tabindex), len(linbits))
	}

	fmt.Println("// Code generated by tools/huffgen from minimp3.h (CC0). DO NOT EDIT.")
	fmt.Println("// Huffman 码表为 ISO/IEC 11172-3 Table B.7 的协议事实;生成器与出处见")
	fmt.Println("// tools/huffgen。ISO 标准文本到位后须逐字核对。")
	fmt.Println()
	fmt.Println("package gl3d")
	fmt.Println()

	pairLists := make([][]pairEntry, 32)
	for t := 1; t < 32; t++ {
		start := tabindex[t]
		if start == 0 {
			continue // 表 4 与 14 未定义
		}
		end := len(tabs)
		for _, v := range tabindex[t+1:] {
			if v > start && v < end {
				end = v
			}
		}
		var out []pairEntry
		walkPairs(tabs[start:end], 0, 5, 0, 0, &out)
		checkCode(fmt.Sprintf("table %d", t), len(out), func(i int) (int, int) { return out[i].code, out[i].length })
		fmt.Fprintf(os.Stderr, "table %d: %d entries\n", t, len(out))
		pairLists[t] = out
	}

	fmt.Println("// huffEntry 是 big_values 区的一对谱值码字。")
	fmt.Println("type huffEntry struct {")
	fmt.Println("\tcode   uint32")
	fmt.Println("\tlength uint8")
	fmt.Println("\tx, y   uint8")
	fmt.Println("}")
	fmt.Println()
	for t, list := range pairLists {
		if list == nil {
			continue
		}
		fmt.Printf("var huffTable%d = []huffEntry{\n", t)
		for _, e := range list {
			fmt.Printf("\t{0x%04x, %2d, %2d, %2d},\n", e.code, e.length, e.x, e.y)
		}
		fmt.Println("}")
		fmt.Println()
	}
	fmt.Println("var huffBigTables = [32][]huffEntry{")
	for t := 0; t < 32; t++ {
		if pairLists[t] != nil {
			fmt.Printf("\t%d: huffTable%d,\n", t, t)
		}
	}
	fmt.Println("}")
	fmt.Println()
	fmt.Println("// huffLinbits 是各表的 linbits(值为 15 时的扩展位数)。")
	fmt.Println("var huffLinbits = [32]uint8{")
	for i, v := range linbits {
		fmt.Printf("\t%d: %d,\n", i, v)
	}
	fmt.Println("}")

	quads := make([][]quadEntry, 2)
	for i, cb := range [][]int{tab32, tab33} {
		var out []quadEntry
		walkQuads(cb, 0, 4, 0, 0, &out)
		checkCode(fmt.Sprintf("count1 table %d", i), len(out), func(j int) (int, int) { return out[j].code, out[j].length })
		quads[i] = out
	}
	fmt.Println()
	fmt.Println("// quadEntry 是 count1 区的四元组码字;flags 的 bit i 置位表示第 i 个")
	fmt.Println("// 值非零(其符号位紧随其后,0=正 1=负)。")
	fmt.Println("type quadEntry struct {")
	fmt.Println("\tcode   uint8")
	fmt.Println("\tlength uint8")
	fmt.Println("\tflags  uint8")
	fmt.Println("}")
	fmt.Println()
	for i, list := range quads {
		fmt.Printf("var huffQuad%c = []quadEntry{\n", 'A'+i)
		for _, e := range list {
			fmt.Printf("\t{0x%02x, %2d, 0x%x},\n", e.code, e.length, e.flags)
		}
		fmt.Println("}")
		fmt.Println()
	}
}
