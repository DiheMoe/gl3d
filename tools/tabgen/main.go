// Command tabgen 从 minimp3.h(CC0)提取 scalefactor band 宽度表与相关常数,
// 生成 sfb_tables.go。在仓库根目录运行:
//
//	go -C tools run ./tabgen /path/to/minimp3.h | gofmt > sfb_tables.go
package main

import (
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

func extractCArray(src, name string) []int {
	re := regexp.MustCompile(`(?s)` + regexp.QuoteMeta(name) + `(?:\[[^\]]*\])+\s*=\s*\{(.*?)\};`)
	m := re.FindStringSubmatch(src)
	if m == nil {
		fatal("array %s not found", name)
	}
	body := strings.ReplaceAll(m[1], "{", " ")
	body = strings.ReplaceAll(body, "}", " ")
	var out []int
	for _, tok := range strings.Split(body, ",") {
		tok = strings.TrimSpace(tok)
		if tok == "" {
			continue
		}
		v, err := strconv.Atoi(tok)
		if err != nil {
			fatal("array %s: bad token %q", name, tok)
		}
		out = append(out, v)
	}
	return out
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "tabgen: "+format+"\n", args...)
	os.Exit(1)
}

// extractCRows 抽取二维数组,按内层大括号分行;短行按声明列数补零(C 语义)。
func extractCRows(src, name string) ([][]int, error) {
	re := regexp.MustCompile(`(?s)` + regexp.QuoteMeta(name) + `\[(\d+)\]\[(\d+)\]\s*=\s*\{(.*?)\};`)
	m := re.FindStringSubmatch(src)
	if m == nil {
		return nil, fmt.Errorf("array %s not found", name)
	}
	nRows, _ := strconv.Atoi(m[1])
	nCols, _ := strconv.Atoi(m[2])
	rowRe := regexp.MustCompile(`\{([^}]*)\}`)
	parts := rowRe.FindAllStringSubmatch(m[3], -1)
	if len(parts) != nRows {
		return nil, fmt.Errorf("%s: got %d row groups, want %d", name, len(parts), nRows)
	}
	out := make([][]int, nRows)
	for r, part := range parts {
		row := make([]int, 0, nCols)
		for _, tok := range strings.Split(part[1], ",") {
			tok = strings.TrimSpace(tok)
			if tok == "" {
				continue
			}
			v, err := strconv.Atoi(tok)
			if err != nil {
				return nil, fmt.Errorf("%s row %d: bad token %q", name, r, tok)
			}
			row = append(row, v)
		}
		if len(row) > nCols {
			return nil, fmt.Errorf("%s row %d: %d entries exceed %d cols", name, r, len(row), nCols)
		}
		for len(row) < nCols {
			row = append(row, 0)
		}
		out[r] = row
	}
	return out, nil
}

// checkRowSums 校验每行宽度之和为 576:三种块形都铺满一个 granule 的谱线。
func checkRowSums(name string, data [][]int) {
	for r, row := range data {
		sum := 0
		for _, v := range row {
			sum += v
		}
		if sum != 576 {
			fatal("%s row %d: widths sum to %d, want 576", name, r, sum)
		}
	}
}

func emitRows(name string, data [][]int) {
	fmt.Printf("var %s = [%d][%d]uint8{\n", name, len(data), len(data[0]))
	for _, row := range data {
		fmt.Printf("\t{")
		for i, v := range row {
			if i > 0 {
				fmt.Printf(" ")
			}
			fmt.Printf("%3d,", v)
		}
		fmt.Printf("},\n")
	}
	fmt.Println("}")
	fmt.Println()
}

func main() {
	if len(os.Args) != 2 {
		fatal("usage: tabgen /path/to/minimp3.h")
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fatal("%v", err)
	}
	src := string(raw)

	long, err := extractCRows(src, "g_scf_long")
	if err != nil {
		fatal("%v", err)
	}
	short, err := extractCRows(src, "g_scf_short")
	if err != nil {
		fatal("%v", err)
	}
	mixed, err := extractCRows(src, "g_scf_mixed")
	if err != nil {
		fatal("%v", err)
	}
	checkRowSums("g_scf_long", long)
	checkRowSums("g_scf_short", short)
	checkRowSums("g_scf_mixed", mixed)
	partitions := extractCArray(src, "g_scf_partitions")
	if len(partitions) != 3*28 {
		fatal("g_scf_partitions: got %d, want 84", len(partitions))
	}
	mod := extractCArray(src, "g_mod")
	if len(mod) != 24 {
		fatal("g_mod: got %d, want 24", len(mod))
	}
	preamp := extractCArray(src, "g_preamp")
	if len(preamp) != 10 {
		fatal("g_preamp: got %d, want 10", len(preamp))
	}

	fmt.Println("// Code generated by tools/tabgen from minimp3.h (CC0). DO NOT EDIT.")
	fmt.Println("// scalefactor band 表为 ISO/IEC 11172-3 Table B.8 与 13818-3 的协议事实;")
	fmt.Println("// 生成器与出处见 tools/tabgen。ISO 标准文本到位后须逐字核对。")
	fmt.Println("//")
	fmt.Println("// 行为说明:表内容为每个 scalefactor band 的宽度(采样数);短块表按窗口")
	fmt.Println("// 交错(13 带 x 3 窗,末位为 0 哨兵);混合块表为 8/6 个长带宽 + 30 个短带宽。")
	fmt.Println("// 行索引 sr_idx = 版本内采样率序号 + (MPEG-2.5:0, MPEG-2:3, MPEG-1:6),")
	fmt.Println("// 非零再减 1(MPEG-2.5 的 11025 与 12000 Hz 共用第 0 行)。")
	fmt.Println()
	fmt.Println("package gl3d")
	fmt.Println()

	emitRows("sfbLongWidths", long)
	emitRows("sfbShortWidths", short)
	emitRows("sfbMixedWidths", mixed)

	fmt.Println("// scfPartitions 是 scalefactor 分段的带数表(三段块形:长/短/混合 x")
	fmt.Println("// LSF 的 7 组混合基数变体,每 4 个一组)。")
	emitRows("scfPartitions", [][]int{partitions[0:28], partitions[28:56], partitions[56:84]})

	fmt.Println("// scfMod 是 LSF scalefac_compress 混合基数展开的模数表。")
	emitRows("scfMod", [][]int{mod})

	fmt.Println("// pretabTail 是 MPEG-1 preflag 附加表(sfb 11..20;ISO 11172-3 pretab)。")
	emitRows("pretabTail", [][]int{preamp})
}
