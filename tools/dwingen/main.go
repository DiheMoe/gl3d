// Command dwingen 从 minimp3.h(CC0,https://github.com/lieff/minimp3)提取
// ISO/IEC 11172-3 附录 B Table 3-B.3 的 512 点合成窗 D,生成 synthesis_window.go。
// 在仓库根目录运行:
//
//	go -C tools run ./dwingen /path/to/minimp3.h | gofmt > synthesis_window.go
//
// minimp3 以 2^-16 为单位的整数存放窗系数(ISO 表的 9 位小数是这些值的舍入),
// 分在 mp3d_synth 的 g_win 与 mp3d_synth_pair 两处。下标按 ISO 的合成定义推得:
// V 由 32 点 DCT-II X 给出(V[i] 在 i<16 时为 X[16+i],i=16 时为 0,17≤i<48 时
// 为 −X[48−i],i≥48 时为 −X[i−48]),输出 j 的第 m 项是 D[j+32m] 乘 m 个时隙前的
// V[j+32·(m mod 2)]。代入 minimp3 每处常数所乘的时隙延迟与 X 下标,得到:
//
//   - g_win 第 r 行对应输出 j = r+1 与 32−j,第 k 对 (w0, w1) 乘延迟 k 与 15−k:
//     D[j+32k] = w0,D[j+32(15−k)] = w1;输出 32−j 用同一对常数,
//     D[32−j+32k] = −w1,D[32−j+32(15−k)] = −w0。
//   - mp3d_synth_pair 的第一组算输出 0,z[n·64] 是延迟 m = 15−n 的 X[16],
//     D[32m] = (−1)^m·该项系数(含括号内的正负号);第二组算输出 16,只含奇数
//     延迟的 X[0],D[16+32m] = −系数。
//   - D[0] = 0,minimp3 省略了这一项。D[16+64i] 乘恒为 0 的 V[16],minimp3 不存;
//     按窗的对称性取 D[16+64i] = −D[496−64i] 补全,使整表与 ISO 表一致。
package main

import (
	"fmt"
	"os"
	"regexp"
	"strconv"
	"strings"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: dwingen /path/to/minimp3.h")
		os.Exit(1)
	}
	raw, err := os.ReadFile(os.Args[1])
	if err != nil {
		fatal("%v", err)
	}
	src := string(raw)

	var d [512]int
	var set [512]bool
	put := func(n, v int) {
		if set[n] {
			fatal("D[%d] assigned twice", n)
		}
		d[n], set[n] = v, true
	}
	put(0, 0)

	win := ints(section(src, "static const float g_win[] = {", "};"))
	if len(win) != 15*16 {
		fatal("g_win: got %d values, want 240", len(win))
	}
	for r := 0; r < 15; r++ {
		j := r + 1
		for k := 0; k < 8; k++ {
			w0, w1 := win[16*r+2*k], win[16*r+2*k+1]
			put(j+32*k, w0)
			put(j+32*(15-k), w1)
			put(32-j+32*k, -w1)
			put(32-j+32*(15-k), -w0)
		}
	}

	pair := section(src, "static void mp3d_synth_pair(", "\n}\n")
	out0 := section(pair, "{", "pcm[0]")
	out16 := section(pair, "z += 2;", "pcm[16*nch]")

	// 每条累加语句是 a = / a += 后接 (z[A] ± z[B]) * c 或 z[A] * c,A、B 为行号
	// (z[n*64],行 0 写作 z[0])。
	stmt := regexp.MustCompile(`(?m)^\s*a\s*\+?=`)
	two := regexp.MustCompile(`(?m)^\s*a\s*\+?=\s*\(z\[\s*(\d+)(?:\*64)?\]\s*([+-])\s*z\[\s*(\d+)(?:\*64)?\]\)\s*\*\s*(-?\d+);`)
	one := regexp.MustCompile(`(?m)^\s*a\s*\+?=\s*z\[\s*(\d+)(?:\*64)?\]\s*\*\s*(-?\d+);`)

	pairs, singles := two.FindAllStringSubmatch(out0, -1), one.FindAllStringSubmatch(out0, -1)
	if n := len(stmt.FindAllString(out0, -1)); n != len(pairs)+len(singles) || 2*len(pairs)+len(singles) != 15 {
		fatal("synth_pair output 0: %d statements, %d pairs, %d singles", n, len(pairs), len(singles))
	}
	lag0 := func(row, c int) {
		m := 15 - row
		if m < 1 || m > 15 {
			fatal("synth_pair output 0: bad row %d", row)
		}
		if m%2 == 1 {
			c = -c
		}
		put(32*m, c)
	}
	for _, t := range pairs {
		c := atoi(t[4])
		lag0(atoi(t[1]), c)
		if t[2] == "-" {
			c = -c
		}
		lag0(atoi(t[3]), c)
	}
	for _, t := range singles {
		lag0(atoi(t[1]), atoi(t[2]))
	}

	terms := one.FindAllStringSubmatch(out16, -1)
	if n := len(stmt.FindAllString(out16, -1)); n != 8 || len(terms) != 8 {
		fatal("synth_pair output 16: %d statements, %d parsed, want 8", n, len(terms))
	}
	for _, t := range terms {
		m := 15 - atoi(t[1])
		if m < 1 || m%2 == 0 {
			fatal("synth_pair output 16: bad row %s", t[1])
		}
		put(16+32*m, -atoi(t[2]))
	}
	for i := 0; i < 8; i++ {
		put(16+64*i, -d[496-64*i])
	}
	for n, ok := range set {
		if !ok {
			fatal("D[%d] not assigned", n)
		}
	}

	fmt.Println("// Code generated by tools/dwingen from minimp3.h (CC0). DO NOT EDIT.")
	fmt.Println("// 合成窗为 ISO/IEC 11172-3 附录 B Table 3-B.3 的协议常数,以 2^-16 为单位")
	fmt.Println()
	fmt.Println("package gl3d")
	fmt.Println()
	fmt.Println("// synthWindowD[n] = synthWindowQ16[n] / 2^16,换算无舍入。")
	fmt.Println("var synthWindowD = func() (d [512]float64) {")
	fmt.Println("\tfor n, k := range synthWindowQ16 {")
	fmt.Println("\t\td[n] = float64(k) / 65536")
	fmt.Println("\t}")
	fmt.Println("\treturn d")
	fmt.Println("}()")
	fmt.Println()
	fmt.Println("var synthWindowQ16 = [512]int32{")
	for n := 0; n < 512; n += 16 {
		s := make([]string, 16)
		for i := range s {
			s[i] = strconv.Itoa(d[n+i])
		}
		fmt.Printf("\t%s,\n", strings.Join(s, ", "))
	}
	fmt.Println("}")
}

// section 返回 src 中 start 之后、下一个 end 之前的文本。
func section(src, start, end string) string {
	i := strings.Index(src, start)
	if i < 0 {
		fatal("%q not found", start)
	}
	rest := src[i+len(start):]
	j := strings.Index(rest, end)
	if j < 0 {
		fatal("%q not found after %q", end, start)
	}
	return rest[:j]
}

// ints 抽取文本中的全部十进制整数。
func ints(s string) []int {
	var v []int
	for _, f := range regexp.MustCompile(`-?\d+`).FindAllString(s, -1) {
		v = append(v, atoi(f))
	}
	return v
}

func atoi(s string) int {
	v, err := strconv.Atoi(s)
	if err != nil {
		fatal("bad integer %q", s)
	}
	return v
}

func fatal(format string, args ...any) {
	fmt.Fprintf(os.Stderr, "dwingen: "+format+"\n", args...)
	os.Exit(1)
}
